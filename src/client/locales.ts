interface StorageReader { getItem(key: string): string | null }
interface StorageWriter extends StorageReader { setItem(key: string, value: string): void }

export function resolveInitialLanguage(storage?: StorageReader, browserLanguage?: string): LiteratureLanguage {
  let saved: string | null = null
  try { saved = storage?.getItem(LANGUAGE_STORAGE_KEY) ?? null } catch { /* unavailable storage */ }
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  return (browserLanguage ?? '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

function runtimeStorage(): StorageWriter | undefined {
  try { return typeof localStorage === 'undefined' ? undefined : localStorage } catch { return undefined }
}

let language = resolveInitialLanguage(
  runtimeStorage(),
  typeof navigator === 'undefined' ? 'en-US' : navigator.language,
)
const listeners = new Set<() => void>()

export function getLanguage(): LiteratureLanguage { return language }

export function setLanguage(next: LiteratureLanguage, storage: StorageWriter | undefined = runtimeStorage()): void {
  language = next
  try { storage?.setItem(LANGUAGE_STORAGE_KEY, next) } catch { /* unavailable storage */ }
  for (const listener of listeners) listener()
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener)
  return () => { listeners.delete(listener) }
}

export function t(key: LiteratureKey): string {
  return language === 'zh-CN' ? zh[key] : en[key]
}

export function localeKeys(): Record<LiteratureLanguage, string[]> {
  return {
    'zh-CN': Object.keys(zh).sort(),
    'en-US': Object.keys(en).sort(),
  }
}
